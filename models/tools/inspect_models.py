"""Describe every committed ONNX model and write models/tools/model-io.md.

    python -I models/tools/inspect_models.py

For each file: size, SHA-256, IR version, opset, producer, input/output names, shapes and dtypes,
and one sample run on the golden portrait (prepared exactly as reference_pipeline does), with the
shapes actually returned. Also checks the facts the Java port relies on and fails if one is wrong.
"""
import hashlib
import sys
from pathlib import Path

import numpy as np
import onnx
import onnxruntime as ort

TOOLS = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOLS))
import reference_pipeline as rp  # noqa: E402

PORTRAIT = TOOLS.parent.parent / "liveness-analyzer" / "src" / "test" / "resources" / "golden" / "portrait_frontal.png"
OUT = TOOLS / "model-io.md"
ROLES = {
    rp.YUNET_FILE: "face detector (YuNet 2026may, OpenCV Zoo)",
    rp.MESH_FILE: "478-point face mesh with irises (MediaPipe FaceMesh V2, face_landmarker.task float16/1, converted)",
    rp.PAD_V2_FILE: "PAD, MiniFASNetV2, crop scale 2.7 (Silent-Face, exported)",
    rp.PAD_V1SE_FILE: "PAD, MiniFASNetV1SE, crop scale 4.0 (Silent-Face, exported)",
}


def dims(shape):
    return "[" + ", ".join(str(d) if isinstance(d, int) else f"'{d}'" for d in shape) + "]"


def sample_inputs():
    """One real input per model, built from the golden portrait by the reference pipeline."""
    bgr = rp.imread_bgr(PORTRAIT)
    yunet_tensor, info = rp.YuNet.prepare(bgr)
    face = rp.count_faces(rp.YuNet(rp.MODELS / rp.YUNET_FILE).detect(bgr))[1]
    ibox = rp.pad_box(face["box"])
    h, w = bgr.shape[:2]
    return {
        rp.YUNET_FILE: {"input": yunet_tensor},
        rp.MESH_FILE: {rp.MESH_INPUT: rp.mesh_input(bgr, rp.mesh_roi(face))},
        rp.PAD_V2_FILE: {"input": rp.pad_input(bgr, rp.get_new_box(w, h, ibox, rp.PAD_V2_SCALE))},
        rp.PAD_V1SE_FILE: {"input": rp.pad_input(bgr, rp.get_new_box(w, h, ibox, rp.PAD_V1SE_SCALE))},
    }


def describe_run(name, outputs):
    if name == rp.YUNET_FILE:
        scores = np.sqrt(np.clip(outputs["cls_8"], 0, 1) * np.clip(outputs["obj_8"], 0, 1))
        return f"best stride-8 score {float(scores.max()):.4f}"
    if name == rp.MESH_FILE:
        first = [round(float(v), 3) for v in outputs[rp.MESH_LANDMARKS].ravel()[:3]]
        return (f"sigmoid({rp.MESH_FLAG}) = {rp.sigmoid(float(outputs[rp.MESH_FLAG].ravel()[0])):.6f}; "
                f"first point (x, y, z) = {first}; Identity_2 (unused) = {float(outputs['Identity_2'].ravel()[0]):.4f}")
    logits = outputs["output"][0]
    return (f"logits {[round(float(v), 4) for v in logits]}, "
            f"softmax {[round(float(v), 4) for v in rp.softmax(logits)]} (index 1 = real)")


def main():
    inputs = sample_inputs()
    lines = ["# Model I/O (generated by `inspect_models.py`; do not edit by hand)", "",
             f"onnxruntime {ort.__version__}, onnx {onnx.__version__}. Sample runs use "
             "`liveness-analyzer/src/test/resources/golden/portrait_frontal.png`, prepared by `reference_pipeline.py`.", ""]
    problems = []
    total = 0
    for name, role in ROLES.items():
        path = rp.MODELS / name
        data = path.read_bytes()
        total += len(data)
        model = onnx.load_from_string(data)
        opsets = ", ".join(f"{d or 'ai.onnx'} {v}" for d, v in ((o.domain, o.version) for o in model.opset_import))
        sess = ort.InferenceSession(data, providers=["CPUExecutionProvider"])
        names = [o.name for o in sess.get_outputs()]
        outputs = dict(zip(names, sess.run(names, inputs[name])))
        lines += [f"## `{name}`", "", f"{role}", "",
                  f"- size: {len(data):,} bytes",
                  f"- sha256: `{hashlib.sha256(data).hexdigest()}`",
                  f"- IR version {model.ir_version}; opset {opsets}; producer {model.producer_name} {model.producer_version}".rstrip(),
                  "", "| kind | name | declared shape | dtype | sample-run shape |", "|---|---|---|---|---|"]
        for i in sess.get_inputs():
            lines.append(f"| input | `{i.name}` | {dims(i.shape)} | {i.type} | {list(inputs[name][i.name].shape)} |")
        for o in sess.get_outputs():
            lines.append(f"| output | `{o.name}` | {dims(o.shape)} | {o.type} | {list(outputs[o.name].shape)} |")
        lines += ["", f"Sample run: {describe_run(name, outputs)}", ""]

        if name == rp.YUNET_FILE:
            shp = sess.get_inputs()[0].shape
            if not (isinstance(shp[2], str) and isinstance(shp[3], str)):
                problems.append(f"YuNet H/W not symbolic: {shp}")
            expect = {f"{k}_{s}": n for k, n in (("cls", 1), ("obj", 1), ("bbox", 4), ("kps", 10)) for s in rp.YUNET_STRIDES}
            for o in sess.get_outputs():
                if expect.get(o.name) != outputs[o.name].shape[2] or outputs[o.name].shape[0] != 1:
                    problems.append(f"YuNet output {o.name} shape {outputs[o.name].shape}")
            if len(names) != 12 or set(names) != set(expect):
                problems.append(f"YuNet outputs {names}")
        if name == rp.MESH_FILE:
            # tf2onnx makes the batch dimension symbolic; we always feed batch 1.
            if [i.name for i in sess.get_inputs()] != [rp.MESH_INPUT] or sess.get_inputs()[0].shape[1:] != [256, 256, 3]:
                problems.append(f"mesh input is not {rp.MESH_INPUT} [N,256,256,3]")
            if outputs.get(rp.MESH_LANDMARKS) is None or outputs[rp.MESH_LANDMARKS].size != 1434 \
                    or outputs.get(rp.MESH_FLAG) is None or outputs[rp.MESH_FLAG].size != 1:
                problems.append(f"mesh outputs {names}")
        if name in (rp.PAD_V2_FILE, rp.PAD_V1SE_FILE):
            if sess.get_inputs()[0].name != "input" or sess.get_inputs()[0].shape != [1, 3, 80, 80] \
                    or names != ["output"] or outputs["output"].shape != (1, 3):
                problems.append(f"{name} I/O differs from input [1,3,80,80] / output [1,3]")
    lines += [f"Total size of the four models: {total:,} bytes ({total / 1048576:.2f} MiB).", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    if problems:
        sys.exit("FACT CHECK FAILED:\n  " + "\n  ".join(problems))
    print("fact checks: ok")


if __name__ == "__main__":
    main()
