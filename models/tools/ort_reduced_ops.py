"""F10b: the operator config for a reduced ONNX Runtime build (--include_ops_by_config), from the committed models.

    python models/tools/ort_reduced_ops.py [--models models] [--out models/tools/ort-reduced-ops.config]

The config lists, per domain and opset ("domain;opset;Op1,Op2,..."), the operators of every ONNX model in --models,
plus the ones ONNX Runtime adds when it optimizes them at load time: the engine opens every model with ALL_OPT
(OnnxModels), which can fuse nodes into contrib operators the models do not contain (for example FusedConv). Those
come from this desktop onnxruntime's own optimization at ORT_ENABLE_ALL on the CPU. Its x86-only layout operators
(com.microsoft.nchwc) are left out: an arm64 build does not use them. The models stay ONNX: no .ort conversion, so
the signed bundle is unchanged. Needs the onnx and onnxruntime packages (the mosip-liveness venv); the optimized
copies go to a temporary folder and are deleted.
"""
import argparse
import collections
import sys
import tempfile
from pathlib import Path

import onnx
import onnxruntime as ort

ROOT = Path(__file__).resolve().parents[2]
X86_ONLY = {"com.microsoft.nchwc"}


def opsets_of(model):
    out = {(o.domain or "ai.onnx"): o.version for o in model.opset_import}
    return out


def collect(graph, opsets, ops, skipped):
    """Adds each node's operator, subgraphs (If, Loop, Scan) included, under its domain's opset."""
    for node in graph.node:
        domain = node.domain or "ai.onnx"
        key = (domain, opsets.get(domain, 1))
        (skipped if domain in X86_ONLY else ops)[key].add(node.op_type)
        for attr in node.attribute:
            if attr.HasField("g"):
                collect(attr.g, opsets, ops, skipped)
            for g in attr.graphs:
                collect(g, opsets, ops, skipped)


def reduced_ops(models_dir):
    """({(domain, opset): ops} of the models plus their load-time optimization, {added by the optimizer}, {left out})."""
    own, ops, skipped = (collections.defaultdict(set) for _ in range(3))
    paths = sorted(Path(models_dir).glob("*.onnx"))
    if not paths:
        raise SystemExit(f"no .onnx files in {models_dir}")
    with tempfile.TemporaryDirectory() as tmp:
        for path in paths:
            model = onnx.load(str(path), load_external_data=False)
            collect(model.graph, opsets_of(model), own, skipped)
            so = ort.SessionOptions()
            so.graph_optimization_level = ort.GraphOptimizationLevel.ORT_ENABLE_ALL
            so.log_severity_level = 3  # the optimized copy is only read here: no warning about hardware-specific layouts
            so.optimized_model_filepath = str(Path(tmp) / path.name)
            ort.InferenceSession(str(path), so, providers=["CPUExecutionProvider"])
            optimized = onnx.load(so.optimized_model_filepath, load_external_data=False)
            collect(optimized.graph, opsets_of(optimized), ops, skipped)
    for key, names in own.items():
        ops[key] |= names
    added = {k: sorted(v - own.get(k, set())) for k, v in ops.items() if v - own.get(k, set())}
    return ops, added, skipped, [p.name for p in paths]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--models", default=str(ROOT / "models"))
    ap.add_argument("--out", default=str(ROOT / "models" / "tools" / "ort-reduced-ops.config"))
    args = ap.parse_args(argv)
    ops, added, skipped, names = reduced_ops(args.models)
    lines = [f"{d};{v};{','.join(sorted(t))}" for (d, v), t in sorted(ops.items())]
    header = ["# F10b: the operators of " + ", ".join(names) + ",",
              f"# plus those ONNX Runtime {ort.__version__} adds at ORT_ENABLE_ALL; for --include_ops_by_config.",
              "# Generated by models/tools/ort_reduced_ops.py; x86-only layout operators (com.microsoft.nchwc) left out."]
    Path(args.out).write_text("\n".join(header + lines) + "\n", encoding="utf-8", newline="\n")
    print("\n".join(lines))
    print(f"added by the optimizer: {added or 'none'}")
    print(f"x86-only, left out: {dict((k, sorted(v)) for k, v in skipped.items()) or 'none'}")
    print(f"{sum(len(t) for t in ops.values())} operators in {len(lines)} lines -> {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
